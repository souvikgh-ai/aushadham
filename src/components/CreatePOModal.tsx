import React, { useState, useEffect } from 'react';
import { X, Plus, Trash2, Truck, AlertCircle } from 'lucide-react';
import { usePharmacy } from '../context/PharmacyContext';

interface CreatePOModalProps {
  isOpen: boolean;
  onClose: () => void;
  initialMedicineId?: string;
  initialSupplierId?: string;
  initialQuantity?: number;
}

export const CreatePOModal: React.FC<CreatePOModalProps> = ({
  isOpen,
  onClose,
  initialMedicineId,
  initialSupplierId,
  initialQuantity,
}) => {
  const { medicines, suppliers, createPurchaseOrder } = usePharmacy();

  const [selectedSupplierId, setSelectedSupplierId] = useState(initialSupplierId || suppliers[0]?.id || '');
  const [items, setItems] = useState<{ medicineId: string; quantity: number }[]>([
    {
      medicineId: initialMedicineId || medicines[0]?.id || '',
      quantity: initialQuantity || 50,
    }
  ]);
  const [notes, setNotes] = useState('');
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (initialMedicineId) {
      const med = medicines.find(m => m.id === initialMedicineId);
      if (med) {
        setSelectedSupplierId(med.supplierId || suppliers[0]?.id || '');
        setItems([{ medicineId: med.id, quantity: initialQuantity || 50 }]);
      }
    }
  }, [initialMedicineId, initialQuantity, medicines, suppliers]);

  if (!isOpen) return null;

  const supplier = suppliers.find(s => s.id === selectedSupplierId) || suppliers[0];

  const handleAddItem = () => {
    const availableMed = medicines.find(m => !items.some(i => i.medicineId === m.id));
    if (availableMed) {
      setItems([...items, { medicineId: availableMed.id, quantity: 40 }]);
    }
  };

  const handleRemoveItem = (index: number) => {
    setItems(items.filter((_, i) => i !== index));
  };

  const handleUpdateItem = (index: number, medicineId: string, quantity: number) => {
    const updated = [...items];
    updated[index] = { medicineId, quantity };
    setItems(updated);
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);

    if (items.length === 0) {
      setError('Please add at least one medicine item to the purchase order.');
      return;
    }

    const poItems = items.map(item => {
      const med = medicines.find(m => m.id === item.medicineId);
      return {
        medicineId: item.medicineId,
        medicineName: med?.name || 'Unknown',
        orderedQuantity: item.quantity,
        unitPurchasePrice: med?.purchasePrice || 15,
      };
    });

    createPurchaseOrder({
      supplierId: supplier.id,
      supplierName: supplier.name,
      items: poItems,
      notes: notes.trim() || undefined,
      autoGeneratedReason: initialMedicineId ? 'Generated from AI Reorder Recommendation.' : undefined,
    });

    onClose();
  };

  const totalCost = items.reduce((sum, item) => {
    const med = medicines.find(m => m.id === item.medicineId);
    return sum + (item.quantity * (med?.purchasePrice || 15));
  }, 0);

  return (
    <div className="fixed inset-0 bg-slate-900/60 backdrop-blur-sm z-50 flex items-center justify-center p-4">
      <div className="bg-white rounded-2xl max-w-xl w-full p-6 space-y-4 shadow-2xl">
        <div className="flex items-center justify-between pb-3 border-b border-slate-200">
          <div>
            <h2 className="text-base font-black text-slate-900">Create Supplier Purchase Order</h2>
            <p className="text-xs text-slate-500">Replenish pharmacy stock from licensed distributors</p>
          </div>
          <button onClick={onClose} className="p-1 rounded-lg text-slate-400 hover:text-slate-600">
            <X className="w-5 h-5" />
          </button>
        </div>

        {error && (
          <div className="p-2.5 rounded-xl bg-red-50 border border-red-200 text-red-700 text-xs font-semibold flex items-center gap-1.5">
            <AlertCircle className="w-4 h-4 flex-shrink-0" />
            <span>{error}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-4 text-xs">
          <div>
            <label className="font-bold text-slate-700 block mb-1">Distributor / Supplier</label>
            <select
              value={selectedSupplierId}
              onChange={e => setSelectedSupplierId(e.target.value)}
              className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-200 font-semibold focus:outline-none"
            >
              {suppliers.map(s => (
                <option key={s.id} value={s.id}>
                  {s.name} (Avg Lead Time: {s.averageLeadTime} days)
                </option>
              ))}
            </select>
          </div>

          {/* Items Table */}
          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <span className="font-bold text-slate-700">Order Lines</span>
              <button
                type="button"
                onClick={handleAddItem}
                className="text-[11px] font-bold text-teal-600 hover:text-teal-700 flex items-center gap-1"
              >
                <Plus className="w-3.5 h-3.5" />
                <span>Add Another Medicine</span>
              </button>
            </div>

            <div className="space-y-2 max-h-52 overflow-y-auto pr-1">
              {items.map((item, idx) => {
                const med = medicines.find(m => m.id === item.medicineId);
                return (
                  <div key={idx} className="flex items-center gap-2 p-2 rounded-xl bg-slate-50 border border-slate-200">
                    <div className="flex-1">
                      <select
                        value={item.medicineId}
                        onChange={e => handleUpdateItem(idx, e.target.value, item.quantity)}
                        className="w-full px-2 py-1.5 rounded-lg bg-white border border-slate-200 font-bold text-slate-900 focus:outline-none"
                      >
                        {medicines.map(m => (
                          <option key={m.id} value={m.id}>
                            {m.name} (Cur Stock: {m.currentStock}, Cost: ₹{m.purchasePrice})
                          </option>
                        ))}
                      </select>
                    </div>

                    <div className="w-24">
                      <input
                        type="number"
                        min="1"
                        required
                        value={item.quantity}
                        onChange={e => handleUpdateItem(idx, item.medicineId, parseInt(e.target.value, 10) || 1)}
                        className="w-full px-2 py-1.5 rounded-lg bg-white border border-slate-200 font-black text-center"
                        placeholder="Qty"
                      />
                    </div>

                    <div className="w-20 text-right font-black text-slate-800">
                      ₹{(item.quantity * (med?.purchasePrice || 15)).toLocaleString('en-IN')}
                    </div>

                    {items.length > 1 && (
                      <button
                        type="button"
                        onClick={() => handleRemoveItem(idx)}
                        className="p-1 text-slate-400 hover:text-red-600"
                      >
                        <Trash2 className="w-3.5 h-3.5" />
                      </button>
                    )}
                  </div>
                );
              })}
            </div>
          </div>

          <div>
            <label className="font-bold text-slate-700 block mb-1">Notes / Shipping Instructions</label>
            <input
              type="text"
              placeholder="e.g. Rush delivery requested due to rapid depletion"
              value={notes}
              onChange={e => setNotes(e.target.value)}
              className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-200 font-medium focus:bg-white focus:outline-none"
            />
          </div>

          <div className="p-3 rounded-xl bg-slate-50 border border-slate-200 flex items-center justify-between text-xs">
            <span className="text-slate-600 font-medium">Estimated Order Amount</span>
            <span className="text-base font-black text-slate-900">₹{totalCost.toLocaleString('en-IN')}</span>
          </div>

          <div className="flex items-center justify-end gap-2 pt-2 border-t border-slate-200">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2 rounded-xl font-bold text-slate-600 hover:bg-slate-100"
            >
              Cancel
            </button>
            <button
              type="submit"
              className="px-5 py-2 rounded-xl font-bold bg-teal-600 hover:bg-teal-700 text-white shadow-sm flex items-center gap-1.5"
            >
              <Truck className="w-4 h-4" />
              <span>Dispatch Purchase Order</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
