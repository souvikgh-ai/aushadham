import React, { createContext, useContext, useState, useEffect, useMemo, useCallback } from 'react';
import type { 
  Medicine, 
  MedicineBatch, 
  Supplier, 
  SaleTransaction, 
  InventoryTransaction, 
  PurchaseOrder, 
  PharmacySettings,
  CartItem,
  Recommendation,
  Alert,
  DemandForecast,
  InventoryStatus,
  DosageForm
} from '../types/pharmacy';
import { StorageService } from '../services/storageService';
import { 
  calculateValidStock, 
  calculateAverageDailySales, 
  calculateDaysUntilStockout, 
  generateAIRecommendations, 
  generateInventoryAlerts, 
  generateDemandForecast,
  getPreferredBatchForSale,
  getMedicineInventoryStatus,
  getDaysToExpiry
} from '../services/inventoryEngine';
import confetti from 'canvas-confetti';

export type NavigationPage = 
  | 'dashboard' 
  | 'pos' 
  | 'medicines' 
  | 'inventory' 
  | 'expiry' 
  | 'recommendations' 
  | 'forecast' 
  | 'sales' 
  | 'po' 
  | 'suppliers' 
  | 'alerts' 
  | 'reports' 
  | 'settings';

interface PharmacyContextType {
  // Navigation & UI state
  activePage: NavigationPage;
  setActivePage: (page: NavigationPage) => void;
  selectedMedicineDetail: Medicine | null;
  setSelectedMedicineDetail: (medicine: Medicine | null) => void;
  
  // Data State
  medicines: Medicine[];
  batches: MedicineBatch[];
  suppliers: Supplier[];
  sales: SaleTransaction[];
  inventoryTransactions: InventoryTransaction[];
  purchaseOrders: PurchaseOrder[];
  settings: PharmacySettings;
  cart: CartItem[];

  // Dynamic AI & Computed State
  recommendations: Recommendation[];
  alerts: Alert[];
  demandForecasts: DemandForecast[];
  kpis: {
    totalMedicines: number;
    todaySales: number;
    todayBillsCount: number;
    lowStockCount: number;
    expiringSoonCount: number;
    predictedStockoutCount: number;
    inventoryValue: number;
    recommendationsCount: number;
    healthCounts: {
      healthy: number;
      low: number;
      critical: number;
      expiring: number;
      overstock: number;
    };
  };

  // Actions
  addToCart: (medicine: Medicine, batch?: MedicineBatch, quantity?: number) => { success: boolean; error?: string };
  updateCartQuantity: (index: number, quantity: number) => { success: boolean; error?: string };
  removeFromCart: (index: number) => void;
  clearCart: () => void;
  completeSale: (customerData: {
    name?: string;
    phone?: string;
    doctor?: string;
    paymentMethod: 'CASH' | 'UPI' | 'CARD';
    prescriptionVerified: boolean;
  }) => { success: boolean; sale?: SaleTransaction; error?: string };
  
  createPurchaseOrder: (poData: {
    supplierId: string;
    supplierName: string;
    items: { medicineId: string; medicineName: string; orderedQuantity: number; unitPurchasePrice: number }[];
    notes?: string;
    autoGeneratedReason?: string;
  }) => PurchaseOrder;

  receivePurchaseOrder: (poId: string) => { success: boolean; error?: string };
  
  addMedicine: (data: {
    name: string;
    genericName: string;
    strength: string;
    dosageForm: DosageForm;
    manufacturer: string;
    category: string;
    packSize: string;
    barcode: string;
    sku: string;
    mrp: number;
    sellingPrice: number;
    purchasePrice: number;
    supplierId: string;
    supplierLeadTime: number;
    prescriptionRequired: boolean;
    minimumStock: number;
    safetyStock: number;
    initialBatch?: {
      batchNumber: string;
      manufacturingDate: string;
      expiryDate: string;
      quantity: number;
    };
  }) => Medicine;

  addBatch: (batchData: {
    medicineId: string;
    batchNumber: string;
    manufacturingDate: string;
    expiryDate: string;
    quantity: number;
    purchasePrice: number;
    sellingPrice: number;
    mrp: number;
    supplierId: string;
  }) => MedicineBatch;

  adjustInventory: (
    medicineId: string, 
    batchId: string, 
    quantityChange: number, 
    type: 'ADJUSTMENT' | 'DAMAGE' | 'EXPIRY' | 'RETURN', 
    notes?: string
  ) => void;

  updateSettings: (newSettings: Partial<PharmacySettings>) => void;
  resetToDemoData: () => void;
  resolveAlert: (alertId: string) => void;
  quickOrderForMedicine: (medicineId: string) => void;
  
  // Quick prefill state for PO modal
  quickOrderPrefill: { medicineId?: string; supplierId?: string; quantity?: number } | null;
  setQuickOrderPrefill: (data: { medicineId?: string; supplierId?: string; quantity?: number } | null) => void;
}

const PharmacyContext = createContext<PharmacyContextType | undefined>(undefined);

export const PharmacyProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [activePage, setActivePage] = useState<NavigationPage>('dashboard');
  const [selectedMedicineDetail, setSelectedMedicineDetail] = useState<Medicine | null>(null);
  const [quickOrderPrefill, setQuickOrderPrefill] = useState<{ medicineId?: string; supplierId?: string; quantity?: number } | null>(null);

  // Initialize storage
  const [medicines, setMedicines] = useState<Medicine[]>([]);
  const [batches, setBatches] = useState<MedicineBatch[]>([]);
  const [suppliers, setSuppliers] = useState<Supplier[]>([]);
  const [sales, setSales] = useState<SaleTransaction[]>([]);
  const [inventoryTransactions, setInventoryTransactions] = useState<InventoryTransaction[]>([]);
  const [purchaseOrders, setPurchaseOrders] = useState<PurchaseOrder[]>([]);
  const [settings, setSettings] = useState<PharmacySettings>(StorageService.initialize().settings);
  const [cart, setCart] = useState<CartItem[]>([]);
  const [dismissedAlertIds, setDismissedAlertIds] = useState<Set<string>>(new Set());

  // Initial load
  useEffect(() => {
    const data = StorageService.initialize();
    setMedicines(data.medicines);
    setBatches(data.batches);
    setSuppliers(data.suppliers);
    setSales(data.sales);
    setInventoryTransactions(data.inventoryTransactions);
    setPurchaseOrders(data.purchaseOrders);
    setSettings(data.settings);
  }, []);


  // Compute AI Recommendations
  const recommendations = useMemo(() => {
    if (!medicines.length) return [];
    return generateAIRecommendations(medicines, batches, sales, suppliers, settings);
  }, [medicines, batches, sales, suppliers, settings]);

  // Compute Active Alerts
  const alerts = useMemo(() => {
    if (!medicines.length) return [];
    const rawAlerts = generateInventoryAlerts(medicines, batches, sales, settings);
    return rawAlerts.filter(a => !dismissedAlertIds.has(a.id));
  }, [medicines, batches, sales, settings, dismissedAlertIds]);

  // Compute Demand Forecasts for all medicines
  const demandForecasts = useMemo(() => {
    if (!medicines.length) return [];
    return medicines.map(med => generateDemandForecast(med, sales, batches));
  }, [medicines, sales, batches]);

  // Compute Dashboard KPIs
  const kpis = useMemo(() => {
    const totalMedicines = medicines.length;

    // Today's Sales
    const todayStr = new Date().toISOString().split('T')[0];
    const todayTxs = sales.filter(s => s.timestamp.startsWith(todayStr));
    const todaySales = todayTxs.reduce((sum, s) => sum + s.grandTotal, 0);
    const todayBillsCount = todayTxs.length;

    // Total Inventory Value
    const inventoryValue = batches
      .filter(b => getDaysToExpiry(b.expiryDate) > 0)
      .reduce((sum, b) => sum + (b.quantity * b.purchasePrice), 0);

    // Health Counts
    let lowStockCount = 0;
    let expiringSoonCount = 0;
    let predictedStockoutCount = 0;

    const healthCounts = {
      healthy: 0,
      low: 0,
      critical: 0,
      expiring: 0,
      overstock: 0,
    };

    medicines.forEach(m => {
      const medBatches = batches.filter(b => b.medicineId === m.id);
      const ads = calculateAverageDailySales(m.id, sales, 30);
      const status: InventoryStatus = getMedicineInventoryStatus(m, medBatches, ads, settings);
      const validStock = calculateValidStock(medBatches);
      const daysToStockout = calculateDaysUntilStockout(validStock, ads);

      if (status === 'HEALTHY') healthCounts.healthy++;
      if (status === 'LOW') {
        healthCounts.low++;
        lowStockCount++;
      }
      if (status === 'CRITICAL') {
        healthCounts.critical++;
        predictedStockoutCount++;
      }
      if (status === 'EXPIRING') {
        healthCounts.expiring++;
        expiringSoonCount++;
      }
      if (status === 'OVERSTOCK') healthCounts.overstock++;

      if (daysToStockout !== null && daysToStockout <= m.supplierLeadTime && status !== 'CRITICAL') {
        predictedStockoutCount++;
      }
    });

    // Also count any batch expiring in <= 90 days as expiring soon
    const distinctExpiringMeds = new Set(
      batches
        .filter(b => {
          const days = getDaysToExpiry(b.expiryDate);
          return days > 0 && days <= settings.expiryWarningDays && b.quantity > 0;
        })
        .map(b => b.medicineId)
    );
    expiringSoonCount = Math.max(expiringSoonCount, distinctExpiringMeds.size);

    return {
      totalMedicines,
      todaySales,
      todayBillsCount,
      lowStockCount,
      expiringSoonCount,
      predictedStockoutCount,
      inventoryValue,
      recommendationsCount: recommendations.length,
      healthCounts,
    };
  }, [medicines, batches, sales, settings, recommendations]);

  // Cart Operations
  const addToCart = useCallback((medicine: Medicine, targetBatch?: MedicineBatch, quantity = 1) => {
    const medBatches = batches.filter(b => b.medicineId === medicine.id);
    
    // FEFO: If no batch specified, pick preferred batch with earliest expiry
    let chosenBatch: MedicineBatch | null = targetBatch || null;
    if (!chosenBatch) {
      const preferred = getPreferredBatchForSale(medBatches);
      if (preferred.error || !preferred.batch) {
        return { success: false, error: preferred.error || 'Cannot sell this medicine: No valid batch found.' };
      }
      chosenBatch = preferred.batch;
    }

    // Check expiry
    if (getDaysToExpiry(chosenBatch.expiryDate) <= 0) {
      return { success: false, error: `Batch ${chosenBatch.batchNumber} has expired and cannot be sold.` };
    }

    // Check cart existing quantity
    const existingIndex = cart.findIndex(c => c.medicine.id === medicine.id && c.selectedBatch.id === chosenBatch!.id);
    const currentCartQty = existingIndex > -1 ? cart[existingIndex].quantity : 0;
    const requestedTotal = currentCartQty + quantity;

    if (requestedTotal > chosenBatch.quantity) {
      return { 
        success: false, 
        error: `Only ${chosenBatch.quantity} units available in Batch ${chosenBatch.batchNumber} (Requested: ${requestedTotal}).` 
      };
    }

    if (existingIndex > -1) {
      const updated = [...cart];
      updated[existingIndex].quantity = requestedTotal;
      setCart(updated);
    } else {
      setCart(prev => [...prev, {
        medicine,
        selectedBatch: chosenBatch!,
        quantity,
        discountPercent: 0,
      }]);
    }

    return { success: true };
  }, [batches, cart]);

  const removeFromCart = useCallback((index: number) => {
    setCart(prev => prev.filter((_, i) => i !== index));
  }, []);

  const updateCartQuantity = useCallback((index: number, quantity: number) => {
    if (quantity <= 0) {
      removeFromCart(index);
      return { success: true };
    }

    const item = cart[index];
    if (!item) return { success: false, error: 'Item not found in cart.' };

    if (quantity > item.selectedBatch.quantity) {
      return { 
        success: false, 
        error: `Only ${item.selectedBatch.quantity} units available in batch ${item.selectedBatch.batchNumber}.` 
      };
    }

    const updated = [...cart];
    updated[index] = { ...item, quantity };
    setCart(updated);
    return { success: true };
  }, [cart, removeFromCart]);

  const clearCart = useCallback(() => {
    setCart([]);
  }, []);

  // Complete Sale & Trigger Real-Time AI Updates
  const completeSale = useCallback((customerData: {
    name?: string;
    phone?: string;
    doctor?: string;
    paymentMethod: 'CASH' | 'UPI' | 'CARD';
    prescriptionVerified: boolean;
  }) => {
    const result = StorageService.processSale(
      cart,
      customerData,
      medicines,
      batches,
      sales,
      inventoryTransactions
    );

    if (result.error) {
      return { success: false, error: result.error };
    }

    // Update state synchronously
    setBatches(result.updatedBatches);
    setMedicines(result.updatedMedicines);
    setSales(result.updatedSales);
    setInventoryTransactions(result.updatedInventoryTxs);
    clearCart();

    // Trigger celebration confetti
    try {
      confetti({
        particleCount: 50,
        spread: 60,
        origin: { y: 0.8 }
      });
    } catch {
      // Non-critical
    }

    return { success: true, sale: result.newSale };
  }, [cart, medicines, batches, sales, inventoryTransactions, clearCart]);

  // Create Purchase Order
  const createPurchaseOrder = useCallback((poData: {
    supplierId: string;
    supplierName: string;
    items: { medicineId: string; medicineName: string; orderedQuantity: number; unitPurchasePrice: number }[];
    notes?: string;
    autoGeneratedReason?: string;
  }): PurchaseOrder => {
    const poNumber = `PO-${new Date().getFullYear()}-${Math.floor(100 + Math.random() * 900)}`;
    const todayStr = new Date().toISOString().split('T')[0];
    
    // Estimate delivery date based on supplier
    const sup = suppliers.find(s => s.id === poData.supplierId);
    const leadTime = sup ? sup.averageLeadTime : 4;
    const expDate = new Date();
    expDate.setDate(expDate.getDate() + leadTime);

    const totalAmount = poData.items.reduce((sum, item) => sum + (item.orderedQuantity * item.unitPurchasePrice), 0);

    const newPO: PurchaseOrder = {
      id: `po-${Date.now()}`,
      poNumber,
      supplierId: poData.supplierId,
      supplierName: poData.supplierName,
      status: 'Ordered',
      orderDate: todayStr,
      expectedDeliveryDate: expDate.toISOString().split('T')[0],
      items: poData.items.map(i => ({
        medicineId: i.medicineId,
        medicineName: i.medicineName,
        orderedQuantity: i.orderedQuantity,
        unitPurchasePrice: i.unitPurchasePrice,
        total: i.orderedQuantity * i.unitPurchasePrice,
        receivedQuantity: 0,
      })),
      totalAmount,
      notes: poData.notes,
      autoGeneratedReason: poData.autoGeneratedReason,
    };

    const updated = [newPO, ...purchaseOrders];
    setPurchaseOrders(updated);
    StorageService.savePurchaseOrders(updated);
    return newPO;
  }, [suppliers, purchaseOrders]);

  // Receive Purchase Order
  const receivePurchaseOrder = useCallback((poId: string) => {
    const result = StorageService.receivePurchaseOrder(
      poId,
      purchaseOrders,
      medicines,
      batches,
      inventoryTransactions
    );

    if (result.error) {
      return { success: false, error: result.error };
    }

    setPurchaseOrders(result.updatedPOs);
    setMedicines(result.updatedMedicines);
    setBatches(result.updatedBatches);
    setInventoryTransactions(result.updatedInventoryTxs);

    try {
      confetti({
        particleCount: 60,
        spread: 70,
        origin: { y: 0.7 }
      });
    } catch {
      // Non-critical
    }

    return { success: true };
  }, [purchaseOrders, medicines, batches, inventoryTransactions]);

  // Add Medicine
  const addMedicine = useCallback((data: {
    name: string;
    genericName: string;
    strength: string;
    dosageForm: DosageForm;
    manufacturer: string;
    category: string;
    packSize: string;
    barcode: string;
    sku: string;
    mrp: number;
    sellingPrice: number;
    purchasePrice: number;
    supplierId: string;
    supplierLeadTime: number;
    prescriptionRequired: boolean;
    minimumStock: number;
    safetyStock: number;
    initialBatch?: {
      batchNumber: string;
      manufacturingDate: string;
      expiryDate: string;
      quantity: number;
    };
  }): Medicine => {
    const id = `med-${Date.now()}`;
    const timestamp = new Date().toISOString();

    const newMed: Medicine = {
      id,
      name: data.name,
      genericName: data.genericName,
      strength: data.strength,
      dosageForm: data.dosageForm,
      manufacturer: data.manufacturer,
      category: data.category,
      packSize: data.packSize,
      barcode: data.barcode || `890${Math.floor(1000000000 + Math.random() * 8999999999)}`,
      sku: data.sku || `${data.name.slice(0, 3).toUpperCase()}-${Math.floor(100 + Math.random() * 900)}`,
      mrp: data.mrp,
      sellingPrice: data.sellingPrice,
      purchasePrice: data.purchasePrice,
      supplierId: data.supplierId,
      supplierLeadTime: data.supplierLeadTime || 3,
      prescriptionRequired: data.prescriptionRequired,
      minimumStock: data.minimumStock || 20,
      safetyStock: data.safetyStock || 15,
      currentStock: data.initialBatch ? data.initialBatch.quantity : 0,
      createdAt: timestamp,
      updatedAt: timestamp,
    };

    let updatedBatches = [...batches];
    let updatedTxs = [...inventoryTransactions];

    if (data.initialBatch && data.initialBatch.quantity > 0) {
      const newBatch: MedicineBatch = {
        id: `bat-${Date.now()}`,
        medicineId: id,
        batchNumber: data.initialBatch.batchNumber,
        manufacturingDate: data.initialBatch.manufacturingDate,
        expiryDate: data.initialBatch.expiryDate,
        quantity: data.initialBatch.quantity,
        purchasePrice: data.purchasePrice,
        sellingPrice: data.sellingPrice,
        mrp: data.mrp,
        supplierId: data.supplierId,
        createdAt: timestamp,
      };
      updatedBatches.push(newBatch);

      updatedTxs.push({
        id: `itx-init-${Date.now()}`,
        medicineId: id,
        medicineName: data.name,
        batchId: newBatch.id,
        batchNumber: newBatch.batchNumber,
        type: 'PURCHASE',
        quantityChange: data.initialBatch.quantity,
        previousStock: 0,
        newStock: data.initialBatch.quantity,
        referenceId: 'INITIAL-STOCK',
        notes: 'Initial lot entry on medicine registration',
        timestamp,
      });
    }

    const updatedMeds = [newMed, ...medicines];
    setMedicines(updatedMeds);
    setBatches(updatedBatches);
    setInventoryTransactions(updatedTxs);

    StorageService.saveMedicines(updatedMeds);
    StorageService.saveBatches(updatedBatches);
    StorageService.saveInventoryTransactions(updatedTxs);

    return newMed;
  }, [medicines, batches, inventoryTransactions]);

  // Add Batch
  const addBatch = useCallback((batchData: {
    medicineId: string;
    batchNumber: string;
    manufacturingDate: string;
    expiryDate: string;
    quantity: number;
    purchasePrice: number;
    sellingPrice: number;
    mrp: number;
    supplierId: string;
  }): MedicineBatch => {
    const timestamp = new Date().toISOString();
    const newBatch: MedicineBatch = {
      id: `bat-${Date.now()}`,
      ...batchData,
      createdAt: timestamp,
    };

    const updatedBatches = [newBatch, ...batches];
    const med = medicines.find(m => m.id === batchData.medicineId);
    let updatedTxs = [...inventoryTransactions];

    if (med) {
      const prevStock = med.currentStock;
      const newStock = prevStock + batchData.quantity;

      updatedTxs.push({
        id: `itx-bat-${Date.now()}`,
        medicineId: med.id,
        medicineName: med.name,
        batchId: newBatch.id,
        batchNumber: newBatch.batchNumber,
        type: 'PURCHASE',
        quantityChange: batchData.quantity,
        previousStock: prevStock,
        newStock: newStock,
        referenceId: `BATCH-ADD-${newBatch.batchNumber}`,
        notes: `New batch intake (${batchData.quantity} units)`,
        timestamp,
      });

      const updatedMeds = medicines.map(m => m.id === med.id ? { ...m, currentStock: newStock, updatedAt: timestamp } : m);
      setMedicines(updatedMeds);
      StorageService.saveMedicines(updatedMeds);
    }

    setBatches(updatedBatches);
    setInventoryTransactions(updatedTxs);
    StorageService.saveBatches(updatedBatches);
    StorageService.saveInventoryTransactions(updatedTxs);

    return newBatch;
  }, [batches, medicines, inventoryTransactions]);

  // Adjust Inventory (Damages, manual audit, expiry quarantine)
  const adjustInventory = useCallback((
    medicineId: string, 
    batchId: string, 
    quantityChange: number, 
    type: 'ADJUSTMENT' | 'DAMAGE' | 'EXPIRY' | 'RETURN', 
    notes?: string
  ) => {
    const batchIdx = batches.findIndex(b => b.id === batchId);
    const medIdx = medicines.findIndex(m => m.id === medicineId);
    if (batchIdx === -1 || medIdx === -1) return;

    const targetBatch = batches[batchIdx];
    const targetMed = medicines[medIdx];
    const prevBatchQty = targetBatch.quantity;
    const newBatchQty = Math.max(0, prevBatchQty + quantityChange);
    const actualChange = newBatchQty - prevBatchQty;

    const updatedBatches = [...batches];
    updatedBatches[batchIdx] = { ...targetBatch, quantity: newBatchQty };

    const prevMedStock = targetMed.currentStock;
    const newMedStock = Math.max(0, prevMedStock + actualChange);

    const updatedMeds = [...medicines];
    const timestamp = new Date().toISOString();
    updatedMeds[medIdx] = { ...targetMed, currentStock: newMedStock, updatedAt: timestamp };

    const newTx: InventoryTransaction = {
      id: `itx-adj-${Date.now()}`,
      medicineId: targetMed.id,
      medicineName: targetMed.name,
      batchId: targetBatch.id,
      batchNumber: targetBatch.batchNumber,
      type,
      quantityChange: actualChange,
      previousStock: prevMedStock,
      newStock: newMedStock,
      notes: notes || `Stock ${type} on batch ${targetBatch.batchNumber}`,
      timestamp,
    };

    const updatedTxs = [newTx, ...inventoryTransactions];

    setBatches(updatedBatches);
    setMedicines(updatedMeds);
    setInventoryTransactions(updatedTxs);

    StorageService.saveBatches(updatedBatches);
    StorageService.saveMedicines(updatedMeds);
    StorageService.saveInventoryTransactions(updatedTxs);
  }, [batches, medicines, inventoryTransactions]);

  // Update Settings
  const updateSettings = useCallback((newSettings: Partial<PharmacySettings>) => {
    setSettings(prev => {
      const merged = { ...prev, ...newSettings };
      StorageService.saveSettings(merged);
      return merged;
    });
  }, []);

  // Reset to Demo Data
  const resetToDemoData = useCallback(() => {
    const data = StorageService.resetToDemoData();
    setMedicines(data.medicines);
    setBatches(data.batches);
    setSuppliers(data.suppliers);
    setSales(data.sales);
    setPurchaseOrders(data.purchaseOrders);
    setInventoryTransactions(data.inventoryTransactions);
    setSettings(data.settings);
    setCart([]);
    setDismissedAlertIds(new Set());
    setSelectedMedicineDetail(null);
  }, []);

  // Dismiss/Resolve Alert
  const resolveAlert = useCallback((alertId: string) => {
    setDismissedAlertIds(prev => new Set(prev).add(alertId));
  }, []);

  // Quick Order helper: Prefill PO modal
  const quickOrderForMedicine = useCallback((medicineId: string) => {
    const med = medicines.find(m => m.id === medicineId);
    if (!med) return;
    const rec = recommendations.find(r => r.medicineId === medicineId);
    const qty = rec ? rec.recommendedOrderQuantity : Math.max(30, med.safetyStock * 2);
    setQuickOrderPrefill({
      medicineId: med.id,
      supplierId: med.supplierId,
      quantity: qty,
    });
    setActivePage('po');
  }, [medicines, recommendations]);

  return (
    <PharmacyContext.Provider value={{
      activePage,
      setActivePage,
      selectedMedicineDetail,
      setSelectedMedicineDetail,
      medicines,
      batches,
      suppliers,
      sales,
      inventoryTransactions,
      purchaseOrders,
      settings,
      cart,
      recommendations,
      alerts,
      demandForecasts,
      kpis,
      addToCart,
      updateCartQuantity,
      removeFromCart,
      clearCart,
      completeSale,
      createPurchaseOrder,
      receivePurchaseOrder,
      addMedicine,
      addBatch,
      adjustInventory,
      updateSettings,
      resetToDemoData,
      resolveAlert,
      quickOrderForMedicine,
      quickOrderPrefill,
      setQuickOrderPrefill,
    }}>
      {children}
    </PharmacyContext.Provider>
  );
};

export const usePharmacy = () => {
  const context = useContext(PharmacyContext);
  if (!context) {
    throw new Error('usePharmacy must be used within a PharmacyProvider');
  }
  return context;
};
